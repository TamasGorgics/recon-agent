// Split is one versioned eval split. Dev is for prompt/model iteration, Test is
// held out for reporting and the CI gate, and Injection is the adversarial
// memo suite.
type Split string

const (
	// Dev is the prompt/model iteration split.
	Dev Split = "dev"
	// Test is the held-out reporting and CI-gate split.
	Test Split = "test"
	// Injection is the adversarial injection-only split.
	Injection Split = "injection"
)

// Splits returns all splits in stable order.
func Splits() []Split { return []Split{Dev, Test, Injection} }

// Valid reports whether s is a known split.
func (s Split) Valid() bool {
	switch s {
	case Dev, Test, Injection:
		return true
	default:
		return false
	}
}

// DefaultGeneratedAt is the fixed fake-clock instant handed to synth. Generate
// never reads the clock, so this value is provenance only and never appears in
// generated bytes.
var DefaultGeneratedAt = time.Date(2026, time.January, 1, 0, 0, 0, 0, time.UTC)

// Config selects one deterministic eval split. The zero value is invalid;
// callers normally start from DefaultConfig.
type Config struct {
	// Split selects the defaults and the truth selection rule.
	Split Split
	// Seed is the synth seed. Dev/Test/Injection defaults are 1/2/3.
	Seed int64
	// Days is the number of generator days.
	Days int
	// Difficulty is easy, realistic, or adversarial.
	Difficulty string
	// Modes is the failure-mode application mix.
	Modes modes.Config
	// Synth is the generator configuration.
	Synth config.SynthConfig
	// Ledger is the adjustment allowlist used to validate truth lines. It must
	// contain the concrete generator-suffixed codes for every dataset
	// currency.
	Ledger config.LedgerConfig
	// Sources is the per-source settlement calendar map. An empty map falls
	// back to the generator config's sources, then to the package defaults.
	Sources map[string]config.SourceConfig
	// Templates is the injection template set. Nil loads the embedded
	// synth/injections set.
	Templates []injections.Template
	// GeneratedAt is the fixed fake-clock instant. It never affects bytes.
	GeneratedAt time.Time
}

// ConfigError is a typed invalid eval dataset configuration.
type ConfigError struct {
	Field  string
	Reason string
}

// Error implements error.
func (e *ConfigError) Error() string {
	return fmt.Sprintf("eval/dataset: config %s: %s", e.Field, e.Reason)
}

// DefaultConfig returns the locked M3-01 defaults for one split.
//
//	split      seed  days  difficulty   applications
//	dev        1     35    realistic    12 per mode, batch_composite 6
//	test       2     35    realistic    30 per mode, batch_composite 15
//	injection  3     16    adversarial  30 injection_memo only
func DefaultConfig(split Split) (Config, error) {
	counts, total, err := defaultApplicationCounts(split)
	if err != nil {
		return Config{}, err
	}
	seed, days, difficulty, err := defaultSplitParameters(split)
	if err != nil {
		return Config{}, err
	}
	synthConfig := config.DefaultSynthConfig()
	return Config{
		Split:       split,
		Seed:        seed,
		Days:        days,
		Difficulty:  difficulty,
		Modes:       modes.Config{Total: total, Counts: counts},
		Synth:       synthConfig,
		Ledger:      DefaultLedgerConfig(synthConfig),
		Sources:     config.DefaultSynthIngestSources(),
		Templates:   nil,
		GeneratedAt: DefaultGeneratedAt,
	}, nil
}

func defaultSplitParameters(split Split) (int64, int, string, error) {
	switch split {
	case Dev:
		return 1, 35, synth.DifficultyRealistic, nil
	case Test:
		return 2, 35, synth.DifficultyRealistic, nil
	case Injection:
		return 3, 16, synth.DifficultyAdversarial, nil
	default:
		return 0, 0, "", &ConfigError{Field: "split", Reason: fmt.Sprintf("unknown split %q", split)}
	}
}

// defaultApplicationCounts returns the locked per-mode application mix. The
// batch_composite count is applications, not truth rows: each application
// emits two truth rows (composite link and missing charge), so 15 applications
// yield the required 30 test scenarios.
func defaultApplicationCounts(split Split) (map[string]int, int, error) {
	if split == Injection {
		return map[string]int{modes.InjectionMemo: 30}, 30, nil
	}
	perMode, batch := 0, 0
	switch split {
	case Dev:
		perMode, batch = 12, 6
	case Test:
		perMode, batch = 30, 15
	default:
		return nil, 0, &ConfigError{Field: "split", Reason: fmt.Sprintf("unknown split %q", split)}
	}
	counts := make(map[string]int, len(modes.AllModes))
	total := 0
	for _, mode := range modes.AllModes {
		count := perMode
		if mode == modes.BatchComposite {
			count = batch
		}
		counts[mode] = count
		total += count
	}
	return counts, total, nil
}

// DefaultLedgerConfig returns the eval adjustment allowlist: the concrete
// generator-suffixed accounts every truth adjustment line targets. The
// unsuffixed internal/config defaults cannot exist in a generated world (Q-25).
func DefaultLedgerConfig(synthConfig config.SynthConfig) config.LedgerConfig {
	accounts := make([]string, 0, 3*len(synthConfig.Currencies))
	for _, currency := range synthConfig.CurrenciesSorted() {
		lower := strings.ToLower(currency)
		accounts = append(accounts,
			"clearing_"+synth.SourcePSP+"_"+lower,
			"fees_expense_"+lower,
			"refunds_expense_"+lower,
		)
	}
	return config.LedgerConfig{AdjustmentAccounts: accounts}
}

// Validate checks a configuration before Build touches generation. It accepts
// an empty Sources map as "use the generator/default calendars".
func (c Config) Validate() error {
	if !c.Split.Valid() {
		return &ConfigError{Field: "split", Reason: fmt.Sprintf("unknown split %q", c.Split)}
	}
	if c.Seed < 0 {
		return &ConfigError{Field: "seed", Reason: "must not be negative"}
	}
	if c.Days <= 0 || c.Days > 3660 {
		return &ConfigError{Field: "days", Reason: "must be between 1 and 3660"}
	}
	switch c.Difficulty {
	case synth.DifficultyEasy, synth.DifficultyRealistic, synth.DifficultyAdversarial:
	default:
		return &ConfigError{
			Field:  "difficulty",
			Reason: fmt.Sprintf("%q is not easy, realistic, or adversarial", c.Difficulty),
		}
	}
	if err := c.Modes.Validate(); err != nil {
		return fmt.Errorf("eval/dataset: config modes: %w", err)
	}
	if err := c.Synth.Validate(); err != nil {
		return fmt.Errorf("eval/dataset: config synth: %w", err)
	}
	sources := c.resolvedSources()
	names := make([]string, 0, len(sources))
	for name := range sources {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := sources[name].Validate(name); err != nil {
			return fmt.Errorf("eval/dataset: config sources: %w", err)
		}
	}
	if c.Modes.Counts[modes.LateSettlement] > 0 {
		if _, ok := sources[synth.SourcePSP]; !ok {
			return &ConfigError{
				Field:  "sources",
				Reason: "late_settlement requires a psp_a calendar",
			}
		}
	}
	if err := validateLedgerAllowlist(c.Ledger, c.Synth); err != nil {
		return err
	}
	if len(c.Templates) > 0 {
		if err := validateTemplates(c.Templates); err != nil {
			return fmt.Errorf("eval/dataset: config templates: %w", err)
		}
	}
	return nil
}

func validateLedgerAllowlist(ledger config.LedgerConfig, synthConfig config.SynthConfig) error {
	var missing []string
	for _, currency := range synthConfig.CurrenciesSorted() {
		lower := strings.ToLower(currency)
		for _, code := range []string{
			"clearing_" + synth.SourcePSP + "_" + lower,
			"fees_expense_" + lower,
			"refunds_expense_" + lower,
		} {
			if !ledger.AllowsAdjustment(code) {
				missing = append(missing, code)
			}
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return &ConfigError{
			Field:  "ledger.adjustment_accounts",
			Reason: "missing concrete generated accounts: " + strings.Join(missing, ", "),
		}
	}
	return nil
}

func validateTemplates(templates []injections.Template) error {
	names := make(map[string]struct{}, len(templates))
	texts := make(map[string]string, len(templates))
	for _, template := range templates {
		name := strings.TrimSpace(template.Name)
		if name == "" || name != template.Name {
			return errors.New("template name must be a non-empty base name without surrounding whitespace")
		}
		if strings.ContainsAny(name, `/\`) {
			return fmt.Errorf("template name %q must not contain a path separator", name)
		}
		if _, duplicate := names[name]; duplicate {
			return fmt.Errorf("template name %q is duplicated", name)
		}
		names[name] = struct{}{}
		if strings.TrimSpace(template.Text) == "" {
			return fmt.Errorf("template %q is blank", name)
		}
		if strings.ContainsRune(template.Text, '\x00') {
			return fmt.Errorf("template %q contains NUL", name)
		}
		if previous, duplicate := texts[template.Text]; duplicate {
			return fmt.Errorf("template %q duplicates %q", name, previous)
		}
		texts[template.Text] = name
	}
	return nil
}

// resolvedSources returns the explicit Sources map, else the generator config's
// map, else the package defaults.
func (c Config) resolvedSources() map[string]config.SourceConfig {
	if len(c.Sources) > 0 {
		return c.Sources
	}
	if len(c.Synth.Sources) > 0 {
		return c.Synth.Sources
	}
	return config.DefaultSynthIngestSources()
}
