package state

import (
	"fmt"
	"strings"
)

// statusMeaning is the fixed description rendered in the generated document.
func statusMeaning(s Status) string {
	switch s {
	case StatusProposed:
		return "Agent-created proposal awaiting policy routing (M4-04/M4-11)."
	case StatusPendingApproval:
		return "Awaiting a human approval decision (M4-11)."
	case StatusApproved:
		return "Approved by a human; awaiting executor apply (M4-06)."
	case StatusAutoApproved:
		return "T0 policy auto-approval; awaiting executor apply (M4-04/M4-06)."
	case StatusApplied:
		return "Applied atomically by the executor (M4-06). Terminal."
	case StatusApplyFailed:
		return "Apply failed; retry or case escalation is owned by M4-06/M4-10. Non-terminal."
	case StatusRejected:
		return "Rejected by a human (M4-11). Terminal."
	case StatusExpired:
		return "Expiry deadline passed before approval, or the proposal was never routed (M4-03). Terminal."
	case StatusSuperseded:
		return "Replaced by a newer proposal or made moot by a late match (M4-10). Terminal."
	default:
		return "Unknown status; not part of the proposal state machine."
	}
}

func reasonDescription(e Edge) string {
	if len(e.ReasonEnum) > 0 {
		return "required: " + strings.Join(e.ReasonEnum, ", ")
	}
	if e.ReasonRequired {
		return "required"
	}
	return "optional"
}

func terminalLabel(s Status) string {
	if Terminal(s) {
		return "yes"
	}
	return "no"
}

// RenderMarkdown renders the canonical proposal state-machine document. The
// output is deterministic: statuses are in spec order and edges use the
// Edges() sort order. It carries no timestamps, paths, or commit hashes.
func RenderMarkdown() []byte {
	var b strings.Builder
	b.WriteString(`<!--
Code generated by tools/state-machine-doc from internal/approval/state; DO NOT EDIT.
Regenerate with: go generate ./internal/approval/state
-->

# Proposal state machine

The proposal state machine is the only place proposal status transitions are
decided and recorded. `)
	b.WriteString("`Transition`")
	b.WriteString(` runs in the caller's transaction; the status/version
update and exactly one `)
	b.WriteString("`proposal.transition`")
	b.WriteString(` audit entry commit or roll back together (FIN-30).

## Statuses

| Status | Terminal | Meaning |
|---|---|---|
`)
	for _, s := range AllStatuses() {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", s, terminalLabel(s), statusMeaning(s))
	}

	b.WriteString(`
## Transitions

The table contains exactly 17 legal edges. Every other pair is illegal and
returns a typed error without writing status, version, or audit. Each edge
permits exactly one actor type; roles and four-eyes are M4-11's contract.

| # | From | To | Actor | Reason | Purpose |
|---|---|---|---|---|---|
`)
	for i, e := range Edges() {
		fmt.Fprintf(&b, "| %d | `%s` | `%s` | `%s` | %s | %s |\n",
			i+1, e.From, e.To, e.Actor, reasonDescription(e), e.Purpose)
	}

	b.WriteString(`
## Version and CAS

` + "`version`" + ` is the transition counter. A caller passes ` + "`ExpectedVersion`" + `;
a mismatch returns ` + "`ErrStale`" + ` before any write. Every accepted transition increments
` + "`version`" + ` by exactly one, and the update is guarded by
` + "`WHERE id = $1 AND version = $expected`" + `. ` + "`state_hash`" + ` is the executor's
re-validation hash (M4-06) and is never touched by this package.

## Audit

Each accepted transition writes exactly one ` + "`proposal.transition`" + ` entry with entity type
` + "`proposal`" + ` in the caller's transaction. ` + "`before`" + ` contains exactly
` + "`status`" + ` and ` + "`version`" + `; ` + "`after`" + ` contains the new ` + "`status`" + ` and
` + "`version`" + `, plus a trimmed ` + "`reason`" + ` when one was supplied. The reason is
audit-only: there is no queryable reason column and no rationale, evidence, payload, amount,
or personal data in the audit payload. The timestamp comes from the injected clock.

## Expiry

` + "`ExpireDue`" + ` transitions only ` + "`proposed`" + ` and ` + "`pending_approval`" + ` rows whose
` + "`expires_at`" + ` is non-NULL and ` + "`<= now`" + ` (inclusive), using the injected clock
(FIN-43). It processes up to 100 rows per call, one short transaction per row with
` + "`FOR UPDATE SKIP LOCKED LIMIT 1`" + `, and is idempotent: a second call finds no due rows.
` + "`approved`" + ` and ` + "`auto_approved`" + ` proposals are never expired here; M4-06 refuses
them at apply time and records ` + "`apply_failed`" + ` with reason ` + "`expired`" + `. Setting the
48-hour policy TTL is owned by M4-04/M4-11; M4-03 only consumes ` + "`expires_at`" + `. No expiry
index is added in M4-03; a partial index is a future optimization.

## Terminal states

` + "`applied`" + `, ` + "`rejected`" + `, ` + "`expired`" + `, and ` + "`superseded`" + ` are terminal:
they have no outgoing edges and return ` + "`ErrTerminalState`" + `. ` + "`apply_failed`" + ` is
deliberately non-terminal.

## apply_failed retry caveat

` + "`apply_failed`" + ` may move to ` + "`approved`" + ` or ` + "`auto_approved`" + ` as a retry edge.
This package only records the edge; M4-06 owns whether a retry is allowed, the retry cap, and
mandatory ` + "`state_hash`" + `/break re-validation. A retry must never bypass a fresh approval
when the policy requires one.
`)
	return []byte(b.String())
}
